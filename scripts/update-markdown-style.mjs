import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const css = readFileSync(require.resolve("github-markdown-css/github-markdown.css"), "utf8");
const license = readFileSync(require.resolve("github-markdown-css/license"), "utf8");
writeFileSync(new URL("../src/markdown-css.ts", import.meta.url),
  `// Generated by scripts/update-markdown-style.mjs from github-markdown-css.\n/*\n${license}\n*/\nexport const markdownCss = ${JSON.stringify(css)};\n`);
